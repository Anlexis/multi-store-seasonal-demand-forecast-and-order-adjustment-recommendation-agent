"""AgentCore Platform v1.0"""

# Node contract (agents_layer_design.md §1):
#  - Extend FunctionNode; implement execute(state, config=None) -> dict
#  - Return ONLY the fields this node changes (never full state)
#  - Return AgentStatus enum constants — never plain strings [A1]
#  - Never import from mediator/, api/, or other agents
#
# RET-C2-344 — OutputFormatNode
# Inner DomainWorkflowGraph node 7: render the final output text from the
# forecast + risk + adjustment data.
#
# ⚠️ The DISCLAIMER block is MANDATORY in EVERY output path (happy,
#    out-of-scope, validation-error). Its absence causes the S-3 gate
#    (OutputValidateNode) to reject the output.
#
# Input state keys:
#   aggregated_forecast, food_waste_risk_flags, order_adjustments  (JSON strings),
#   store_group, sku_category, out_of_scope, validation_error
#
# Output state keys (partial dict):
#   output_text:        str  (includes the DISCLAIMER block)
#   disclaimer_present: bool
#   agent_status:       AgentStatus
#   status:             backbone mirror
#   error_message:      str | None
#
# ADR-005: aggregated_forecast / food_waste_risk_flags / order_adjustments are
#          read back with from_json() (msgpack safety).
#
# S-4: emit_trace_event free-function import.

import logging
from typing import Any, ClassVar, List, Optional

from framework.nodes.function_node import FunctionNode
from framework.schemas.agent_status import AgentStatus
from framework.schemas.trust_level import TrustLevel

from shared.utils.audit_logger import emit_trace_event
from src.schemas.state import from_json, has_failed

logger = logging.getLogger(__name__)

# Closed-set failure label — the caller learns the stage, not the exception.
REASON_RENDER_FAILED = "output_rendering_failed"

# Human-readable sentences for the closed-set labels DataValidateNode
# produces. The mapping lives here because this is the only place a label
# becomes prose; the labels themselves stay values, so a new one that is not
# mapped renders as the generic line rather than leaking its own text.
_VALIDATION_LABEL_TEXT = {
    "unsupported_store_group": "the requested store group is not supported",
    "unsupported_sku_category": "the requested SKU category is not supported",
    "horizon_days_out_of_supported_range": ("the forecast horizon must be between 1 and 90 days"),
}
_GENERIC_VALIDATION_TEXT = "the request did not satisfy the input contract"

# ---------------------------------------------------------------------------
# Mandatory DISCLAIMER block (exact, verbatim — verified by the S-3 gate)
# ---------------------------------------------------------------------------

DISCLAIMER_START = "--- DISCLAIMER ---"
DISCLAIMER_END = "--- END DISCLAIMER ---"

DISCLAIMER = (
    f"{DISCLAIMER_START}\n"
    "This demand forecast is generated by an AI model (TimesFM 2.5 zero-shot) "
    "using synthetic data in v1.\n"
    "Results are for planning reference only and do not constitute guaranteed "
    "demand or compliance advice.\n"
    "For regulatory compliance under 食品ロス削減推進法, consult your compliance team.\n"
    f"{DISCLAIMER_END}"
)

# Supported-combination hint reused by the out-of-scope path. Constants, so
# the refusal tells the caller what IS accepted without repeating what they
# sent.
_SUPPORTED_STORES = "kanto_12, kansai_8, chubu_6, kyushu_5"
_SUPPORTED_SKUS = "yogurt, fresh_bread, chilled_dessert, bento, onigiri"


def _render_happy_path(state: dict[str, Any]) -> str:
    """Render the full demand-forecast report (without the trailing DISCLAIMER)."""
    agg = from_json(state.get("aggregated_forecast"), {}) or {}
    risk_flags = from_json(state.get("food_waste_risk_flags"), []) or []
    adjustments = from_json(state.get("order_adjustments"), []) or []
    store_group = state.get("store_group")
    sku_category = state.get("sku_category")

    horizon = agg.get("horizon_days")
    peak_idx = agg.get("peak_day_index", 0)
    peak_total = agg.get("peak_demand_total", 0)
    store_count = agg.get("store_count", 0)
    model = agg.get("model", "unknown")

    lines: List[str] = []
    lines.append("Demand Forecast Report")
    lines.append(f"Store Group: {store_group} | SKU: {sku_category} | Horizon: {horizon} days")
    lines.append("")
    lines.append("Regional Summary")
    lines.append(f"  Peak Demand Day: Day {peak_idx + 1} | " f"Total: {peak_total} units across {store_count} stores")
    lines.append(f"  Model: {model}")
    lines.append("")

    lines.append("Food Waste Risk (食品ロス法 FY2026)")
    if risk_flags:
        flag = risk_flags[0]
        lines.append(
            f"  SKU: {flag.get('sku_category')} | "
            f"Risk Level: {flag.get('risk_level')} | "
            f"Est. Waste: {flag.get('estimated_waste_units')} units"
        )
        lines.append(f"  Reference: {flag.get('law_reference')}")
    else:
        lines.append("  No food waste risk flags generated.")
    lines.append("")

    lines.append("Order Adjustment Recommendations")
    if adjustments:
        for adj in adjustments:
            lines.append(
                f"  {adj.get('store_id')}: "
                f"current={adj.get('current_order_estimate')} "
                f"-> recommended={adj.get('recommended_order')} "
                f"({adj.get('adjustment_pct', 0.0):+.1f}%) "
                f"[{adj.get('adjustment_reason')}]"
            )
    else:
        lines.append("  No per-store adjustments generated.")
    lines.append("")

    return "\n".join(lines)


class OutputFormatNode(FunctionNode):
    """Render output text from forecast + risk + adjustment data.

    The DISCLAIMER block is appended in ALL output paths:
      - happy path: full report + DISCLAIMER
      - out_of_scope=True: unsupported-combination message + DISCLAIMER
      - validation_error set: validation-failure message + DISCLAIMER

    Sets ``disclaimer_present`` from ``DISCLAIMER_START in output_text`` so the
    S-3 gate (OutputValidateNode) can verify it.

    Output (partial dict): output_text, disclaimer_present, agent_status,
    status, error_message.
    """

    required_trust_level: ClassVar[TrustLevel] = TrustLevel.VERIFIED_EXTERNAL

    def __init__(self, node_config: Optional[dict[str, Any]] = None):
        super().__init__()
        self._node_config = node_config or {}

    def execute(self, state: dict[str, Any]) -> dict[str, Any]:
        if has_failed(state):
            return {}

        try:
            if state.get("out_of_scope") or state.get("validation_error"):
                # The label is a value from a closed set, mapped to prose
                # here. Nothing the caller supplied is interpolated: the
                # requested store group and SKU are named in the label's
                # wording, not echoed, so a value this node rejects cannot
                # travel back out inside the answer.
                label = str(state.get("validation_error") or "")
                explanation = _VALIDATION_LABEL_TEXT.get(label, _GENERIC_VALIDATION_TEXT)
                body = (
                    f"This request could not be answered: {explanation}. "
                    f"Supported store groups: {_SUPPORTED_STORES}. "
                    f"Supported SKU categories: {_SUPPORTED_SKUS}. "
                    "Forecast horizon: 1-90 days."
                )
            else:
                body = _render_happy_path(state)

            output_text = f"{body}\n\n{DISCLAIMER}\n"
            disclaimer_present = DISCLAIMER_START in output_text

            logger.info(
                "OutputFormatNode: rendered output (out_of_scope=%s, disclaimer=%s)",
                bool(state.get("out_of_scope")),
                disclaimer_present,
            )

            emit_trace_event(
                "output_formatted",
                {
                    "out_of_scope": bool(state.get("out_of_scope")),
                    "disclaimer_present": disclaimer_present,
                    "length": len(output_text),
                },
                state,
            )

            return {
                "output_text": output_text,
                "disclaimer_present": disclaimer_present,
                "agent_status": AgentStatus.SUCCESS,
                "status": AgentStatus.SUCCESS.value,
                "error_code": None,
                "error_message": None,
            }
        except Exception as exc:  # noqa: BLE001
            logger.exception("OutputFormatNode: render failed")
            emit_trace_event(
                "output_render_failed",
                {"reason": REASON_RENDER_FAILED, "exception": type(exc).__name__},
                state,
            )
            return {
                "output_text": None,
                "disclaimer_present": False,
                "agent_status": AgentStatus.ERROR,
                "status": AgentStatus.ERROR.value,
                "error_code": REASON_RENDER_FAILED,
                "error_message": REASON_RENDER_FAILED,
            }
